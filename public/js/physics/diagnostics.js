  /**
   * Verifies Power Conservation: P_source ≈ ∑ P_consumed
   */
  static verifyPowerBalance(primaryBattery, circuitResult, components) {
    if (!primaryBattery || !circuitResult || circuitResult.openCircuit) {
      return { isBalanced: true, powerSupplied: 0, powerConsumed: 0, error: 0 };
    }

    const vSource = Number(primaryBattery.properties?.voltage ?? 12);
    const internalR = Math.max(0, Number(primaryBattery.properties?.internalResistance || 0));
    const iTotal = circuitResult.totalCurrent || 0;

    // Total power generated by EMF source
    const powerSupplied = vSource * iTotal;

    let powerConsumed = 0;
    components.forEach(c => {
      if (["resistor", "lamp", "motor_dc", "led", "diode"].includes(c.type)) {
        const v = circuitResult.branchVoltages?.get(c.id) || 0;
        const i = circuitResult.branchCurrents?.get(c.id) || 0;
        powerConsumed += (v * i);
      }
    });

    // Add power lost in internal resistance if realistic battery model
    if (internalR > 0) {
      const pInternalLoss = iTotal * iTotal * internalR;
      powerConsumed += pInternalLoss;
    }

    const error = Math.abs(powerSupplied - powerConsumed);
    const isBalanced = error < 0.05; // 50 mW tolerance

    return { isBalanced, powerSupplied, powerConsumed, error };
  }

  /**
   * Helper: check if actual ≈ expected within relative tolerance
   */
  static approxEqual(actual, expected, relTol = 0.005) {
    if (expected === 0) return Math.abs(actual) < 1e-6;
    if (actual === null || actual === undefined) return expected === null;
    return Math.abs(actual - expected) / Math.abs(expected) < relTol;
  }

